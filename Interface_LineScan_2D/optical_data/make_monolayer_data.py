"""
Mid-IR optical data for the monolayer windows (refractiveindex.info has no mid-IR data for either):

graphene_undoped_Kubo.csv   in-plane n, k of a 0.335 nm slab with the sheet conductivity of undoped graphene
                            (E_F = 0, T = 300 K, Kubo formula as in Falkovsky, J. Phys.: Conf. Ser. 129,
                            012004 (2008); intraband scattering time 100 fs):
                                eps = 1 + i sigma / (eps0 omega t0),   t0 = 0.335 nm
                            out of plane graphene is taken as eps = 1 (pure sheet, no normal current)
hBN_Caldwell_o.csv          hBN in-plane (ordinary) and out-of-plane (extraordinary) n, k from the
hBN_Caldwell_e.csv          Lorentz phonon model of Caldwell et al., Nat. Commun. 5, 5221 (2014):
                                eps = eps_inf (1 + (wLO^2 - wTO^2) / (wTO^2 - w^2 - i w gamma))
                            in-plane:      eps_inf 4.87, wTO 1370, wLO 1610 cm-1, gamma 5 cm-1
                            out of plane:  eps_inf 2.95, wTO  780, wLO  830 cm-1, gamma 4 cm-1

Convention exp(-i omega t): Im eps > 0 is loss (same as JCM and the other csv files).

    python make_monolayer_data.py
"""
import os
import numpy as np
from scipy.integrate import quad

HERE = os.path.dirname(os.path.abspath(__file__))
WL_UM = np.round(np.arange(2.0, 8.0001, 0.01), 4)

e, hbar, kB, eps0, c = 1.602176634e-19, 1.054571817e-34, 1.380649e-23, 8.8541878128e-12, 2.99792458e8


def sigma_graphene(omega, T=300.0, mu=0.0, tau=100e-15):
    """Kubo sheet conductivity (S), exp(-i omega t)."""
    kT = kB*T
    gam = 1/tau
    intra = 1j*2*e**2*kT/(np.pi*hbar**2*(omega + 1j*gam))*np.log(2*np.cosh(mu/(2*kT)))
    G = lambda xi: np.sinh(xi/kT)/(np.cosh(mu/kT) + np.cosh(xi/kT))
    h = hbar*omega/2
    f = lambda xi: (G(xi) - G(h))/((hbar*omega)**2 - 4*xi**2)
    # principal-value-free integrand (numerator vanishes at xi = h); split at the removable point
    integ = quad(f, 0, h, limit=400)[0] + quad(f, h, 2*h, limit=400)[0] + quad(f, 2*h, 60*kT + 4*h, limit=400)[0]
    inter = e**2/(4*hbar)*(G(h) + 1j*4*hbar*omega/np.pi*integ)
    return intra + inter


def lorentz(w_cm, einf, wto, wlo, g):
    return einf*(1 + (wlo**2 - wto**2)/(wto**2 - w_cm**2 - 1j*w_cm*g))


def write(name, header, eps):
    nk = np.sqrt(eps)
    nk = np.where(nk.imag < 0, -nk, nk)
    with open(os.path.join(HERE, name), 'w') as f:
        f.write(header)
        f.write('wavelength_um,n,k\n')
        for w, v in zip(WL_UM, nk):
            f.write(f'{w:g},{v.real:.6g},{v.imag:.6g}\n')


if __name__ == '__main__':
    t0 = 0.335e-9
    om = 2*np.pi*c/(WL_UM*1e-6)
    sig = np.array([sigma_graphene(o) for o in om])
    write('graphene_undoped_Kubo.csv',
          '# Undoped graphene (E_F = 0, T = 300 K, tau = 100 fs), Kubo sheet conductivity (Falkovsky 2008)\n'
          '# as an in-plane permittivity of a t0 = 0.335 nm slab: eps = 1 + i sigma/(eps0 omega t0)\n'
          '# Generated by make_monolayer_data.py. Out of plane: eps = 1.\n',
          1 + 1j*sig/(eps0*om*t0))
    w_cm = 1e4/WL_UM
    write('hBN_Caldwell_o.csv', '# hBN in-plane (ordinary), Lorentz model of Caldwell et al., Nat. Commun. 5, 5221 (2014)\n'
          '# eps_inf 4.87, wTO 1370 cm-1, wLO 1610 cm-1, gamma 5 cm-1. Generated by make_monolayer_data.py.\n',
          lorentz(w_cm, 4.87, 1370.0, 1610.0, 5.0))
    write('hBN_Caldwell_e.csv', '# hBN out-of-plane (extraordinary), Lorentz model of Caldwell et al., Nat. Commun. 5, 5221 (2014)\n'
          '# eps_inf 2.95, wTO 780 cm-1, wLO 830 cm-1, gamma 4 cm-1. Generated by make_monolayer_data.py.\n',
          lorentz(w_cm, 2.95, 780.0, 830.0, 4.0))
    for w in (2.95, 6.1):
        i = int(np.argmin(abs(WL_UM - w)))
        s = sig[i]
        print(f'{w} um: graphene sigma/sigma0 = {s/(e**2/(4*hbar)):.3f}, eps(0.335 nm) = {1 + 1j*s/(eps0*om[i]*t0):.2f}; '
              f'hBN eps_o = {lorentz(w_cm[i], 4.87, 1370., 1610., 5.):.3f}, eps_e = {lorentz(w_cm[i], 2.95, 780., 830., 4.):.3f}')
